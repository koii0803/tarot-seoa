def 마지막카드(손님):
    """이 손님이 마지막에 받은 카드 이름. 없으면 빈 칸."""
    try:
        for 줄 in reversed(손님기록._읽기()):
            if 줄.get("손님") == 손님기록._손님키(손님) and 줄.get("카드"):
                return 줄["카드"]
    except Exception:
        pass
    return ""


def 글짓기(댓글, 손님):
    """종류에 맞는 답. 못 만들면 빈 칸 — 그러면 안 답한다."""
    이름 = 종류(댓글)
    if not 이름:
        return "", ""
    카드 = 마지막카드(손님)
    후보 = 문장.get(이름) or []
    쓸것 = [x for x in 후보 if 카드 or not any("{카드}" in 줄 for 줄 in x)]
    if not 쓸것:
        return "", 이름
    골랐다 = random.choice(쓸것)
    return "\n".join(줄.replace("{카드}", 카드) for 줄 in 골랐다), 이름


