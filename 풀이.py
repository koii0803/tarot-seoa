    글, ok, 문제, n, fact = 쓰기(a.who, a.test, a.type, a.tense, a.style, a.date)
    print("카드: %s %s / 상징: %s" % (fact["카드"], fact["방향"], fact["상징하나"]))
    print("-" * 52)
