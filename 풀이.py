def 부호치우기(글):
    """금지된 부호를 지운다. 검사로 막아 세 번 다시 시키느니 그냥 지우는 게 낫다."""
    줄들 = []
    for 줄 in (글 or "").splitlines():
        줄 = 부호버리기.sub(" ", 줄)
        줄 = re.sub(r"\s+", " ", 줄).strip()
        if 줄:
            줄들.append(줄)
    return "\n".join(줄들)


def 부호검사(글):
    """치우고도 남았으면 알린다. 그물 두 겹."""
    남은 = sorted(set(부호버리기.findall(글 or "")))
    return ["쓰면 안 되는 부호가 있다: %s" % " ".join(남은)] if 남은 else []


