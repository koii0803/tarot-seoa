def claude(prompt, sys_prompt, timeout=240, schema=None):
    """claude -p 로 JSON 하나 받는다. 구독으로 돈다. 도구는 일부러 안 싣는다(토큰 아끼려고)."""
    cmd = ["claude", "-p", prompt, "--output-format", "json",
           "--json-schema", json.dumps(schema or SCHEMA, ensure_ascii=False),
           "--model", MODEL, "--safe-mode", "--system-prompt", sys_prompt,
           "--tools", "Read", "--disallowedTools", "Read"]
    try:
        r = subprocess.run(cmd, capture_output=True, timeout=timeout,
                           encoding="utf-8", errors="replace", stdin=subprocess.DEVNULL)
    except subprocess.TimeoutExpired:
        return {"__오류__": "시간초과"}
    if r.returncode != 0:
        까닭 = (r.stderr or "").strip()
        if not 까닭:
            try:
                까닭 = str(json.loads(r.stdout).get("result", ""))
            except Exception:
                까닭 = (r.stdout or "")[:200]
        return {"__오류__": 까닭[:200]}
    try:
        out = json.loads(r.stdout)
        _토큰기록(out, MODEL)
        본문 = out.get("result", out)
        if isinstance(본문, str):
            본문 = json.loads(본문)
        return 본문
    except Exception as e:
        return {"__오류__": "%s / %s" % (e, (r.stdout or "")[:200])}


