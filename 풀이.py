def _새질문이냐(말, 이전유형):
    """딴 질문인가. 묻는 말이고, 낱말로 잡힌 유형이 앞 질문과 다를 때만. (haiku 안 부른다)"""
    t = (말 or "").strip()
    if not (조립.물음꼴.search(t) or 조립.미래꼴.search(t)):
        return False, 이전유형
    유형, _ = 분류._낱말로(t)
    if 유형 and 유형 not in ("불안", "결정") and _가족(유형) != _가족(이전유형):
        return True, 유형
    return False, 이전유형


_가족표 = {"연애": "마음", "재회": "마음", "관계": "마음", "일": "일", "시험": "일", "돈": "돈"}


def _가족(유형):
    return _가족표.get(유형 or "", 유형 or "")


def 손님이더달래(댓글, 오간말):
    """손님이 한 장 더 달라고 했나. "한 장 더" 를 직접 썼거나, 내가 "뽑아볼까?" 한 뒤에 "응" 했거나."""
    t = (댓글 or "").strip()
    if 한장더꼴.search(t):
        return True
    내마지막 = next((말 for 누가, 말 in reversed(오간말) if 누가 == "나"), "")
    return bool(제안꼴.search(내마지막.splitlines()[-1] if 내마지막 else "") and 긍정꼴.search(t))


def 카드정하기(바탕, 턴, 마지막, 댓글, ask_type, 오간말, 카드들):
    """이번 턴에 어느 카드를 쓸지 (2026-09-25).
    돌려주는 것: (씨앗이름, 고정, 새카드, 더뽑은수)

        1~2턴  같은 카드 (바탕)
        3턴    새 카드, 뒷면 (바탕#3)
        4턴~   앞 카드 그대로 (기록에 적힌 마지막 앞면 카드로 고정)
               단, 손님이 한 장 더 달라거나 · 딴 종류 물음을 던지면 새 카드 (바탕#턴)
               **더 뽑는 건 한 대화에 더뽑기최대 장까지.** AI 가 스스로 뽑는 것도 이 수에 든다

    `오간말` 은 손님기록.지난대화(), `카드들` 은 손님기록.카드들(). 시늉에서 넘겨 쓸 수 있게 밖에서 받는다.
    """
    if 턴 == 1:
        return 바탕, None, True, 0
    앞면 = [(t, c, d) for t, c, d, g in 카드들 if g != "뒷면" and c]
    if 턴 == 2:
        # 카드는 1턴 것 그대로, 씨앗만 바꾼다 — 안 그러면 상징·되물음까지 1턴이랑 똑같이 나온다 (@cola_184 실측)
        if 앞면:
            슬러그 = next((c["slug"] for c in 엔진.CARDS if c["ko"] == 앞면[0][1]), None)
            if 슬러그:
                return "%s#2" % 바탕, (슬러그, 앞면[0][2]), False, 0
        return 바탕, None, False, 0
    if 마지막:
        return "%s#%d" % (바탕, 턴), None, True, 0
    # 4턴 뒤에 카드가 바뀐 횟수 = 지금까지 더 뽑은 수
    더뽑은수 = sum(1 for i in range(1, len(앞면)) if 앞면[i][0] >= 4 and 앞면[i][1:] != 앞면[i - 1][1:])
    지난손님말 = [말 for 누가, 말 in 오간말 if 누가 == "손님"]
    유형 = (분류._낱말로(지난손님말[0])[0] if 지난손님말 else None) or ask_type
    for i, 말 in enumerate(지난손님말[1:], start=2):
        if i <= 2 or i == 손님기록.안내턴:
            continue
        _새, 유형 = _새질문이냐(말, 유형)
    새질문, _ = _새질문이냐(댓글, 유형)
    if (새질문 or 손님이더달래(댓글, 오간말)) and 더뽑은수 < 더뽑기최대:
        return "%s#%d" % (바탕, 턴), None, True, 더뽑은수 + 1
    if 앞면:
        _t, 이름, 방향 = 앞면[-1]
        슬러그 = next((c["slug"] for c in 엔진.CARDS if c["ko"] == 이름), None)
        if 슬러그:
            return "%s#%d" % (바탕, 턴), (슬러그, 방향), False, 더뽑은수
    return 바탕, None, False, 더뽑은수


def 문맥답글(손님, 댓글, ask_type, tense, day=None, tries=TRIES, 턴=5, 글아이디="", 새카드=False,
             고정=None, 더뽑을수=0, 바탕="", 오간말=None):
    """**5턴부터.** 지난 대화를 통째로 넘기고 AI 가 이어서 쓴다.

    1~4턴은 조립(파이썬)이 쓴다. 여기는 **문맥을 읽어야만 되는 자리**다 —
    어긋남 짚기 · 오래된 실 되살리기 · 피한 것 알아채기. 규칙으론 못 한다.
    지침은 `말투.py` 하나에 모아 놨다 (웹이랑 같은 것을 쓴다).
    """
    fact = 엔진.digest(손님, 댓글, ask_type, tense, day, tone="반말", 고정=고정)
    if fact["중지"]:
        return fact["중지문구"], True, [], fact
    if 오간말 is None:
        오간말 = 손님기록.지난대화(손님, 글아이디=글아이디)
    p = 문맥프롬프트(fact, 오간말, 댓글, 새카드=새카드, 더뽑을수=더뽑을수)
    # 톤(5턴~ 사람 대 사람) + 끝맺는 법(남겨두기·단정·되물음)
    시킬말 = (말투.SYS + chr(10) * 2 + 말투.톤(턴)
              + chr(10) * 2 + 말투.끝맺기(턴))
    마지막, 문제 = "", ["안 돌았다"]
    for i in range(1, tries + 1):
        out = claude(p, 시킬말)
        if "__오류__" in out:
            # 시간 초과·사용량 한도 같은 것. **여기서 빈손으로 나가면 그 손님만 멈춘다**
            문제 = ["claude 오류: %s" % out["__오류__"]]
            break
        # AI 가 "한 장 더 뽑자" 했다 (2026-09-25). 새 카드를 쥐여 주고 다시 시킨다. 한 번만
        if out.get("draw_more") and 더뽑을수 > 0 and 바탕:
            fact = 엔진.digest("%s#%d" % (바탕, 턴), 댓글, ask_type, tense, day, tone="반말")
            p = 문맥프롬프트(fact, 오간말, 댓글, 방금뽑음=True)
            더뽑을수 = 0
            continue
        마지막 = 다듬기(out.get("reply") or "")
        # 사고 막는 것만 본다. 줄 수·글자 수는 말투.py 기준
        문제 = (사람글인가(마지막) + 부호검사(마지막)
                + 줄수검사(마지막, 말투.줄수) + 말투.글자수검사(마지막)
                + ["법으로 막힌 말: " + 막 for 막 in 말투.막힌말 if 막 in 마지막.lower()]
                + [x for x in 엔진.말투검사(마지막, "반말") if not x.startswith("애교: ㅋ")])
        문제 += [x for x in 엔진.check_output(마지막, fact, need_question=False)
                 if "상징" not in x]          # 지난 대화에 나온 상징은 허용
        if not 문제:
            return 마지막, True, [], fact
        p += chr(10) + chr(10) + "앞서 쓴 글이 걸렸다: %s" % " / ".join(문제) + chr(10) + "다시 써라."

    # ── AI 가 세 번 다 실패했다. **파이썬이 대신 쓴다** (2026-09-24 사장님 지시) ──
    #   전에는 빈손으로 돌아와서 그 손님만 답을 못 받고 멈췄다.
    #   실제로 @seyraen_ae 가 검사에 세 번 걸려 8시간을 기다렸다.
    #   조립은 이미 규칙을 통과한 문장이라 검사에 안 걸린다. 늦는 것보다 낫다.
    대신 = 조립.조립(fact, 댓글, 턴, 피할줄=조립.쓴줄모으기(글아이디), 새카드=새카드)
    if (대신 or "").strip():
        알림.보내기("AI 가 세 번 다 걸려서 조립으로 대신 썼다 (%d턴) · 걸린 까닭: %s"
                    % (턴, " / ".join(문제)[:150]))
        return 대신, True, ["AI 실패 → 조립으로 대신: %s" % " / ".join(문제)[:100]], fact
    return 마지막, False, 문제, fact


def 한판(손님, 댓글, ask_type=None, tense=None, day=None, tries=TRIES, 조용히=False,
         글아이디="", 내글글=""):
    """댓글 하나에 대한 답글을 **그림까지 붙여서** 내준다 (인수인계 12절 3턴 규칙).

        1·2턴 → 앞면 그림 + 풀이 + 되물음
        3턴   → 뒷면 그림 + 프로필 안내
        4턴~  → 답하지 않는다

    **여기서는 기록하지 않는다.** 실제로 스레드에 내보낸 뒤에
    손님기록.기록하기() 를 부른다. 안 내보냈는데 적으면 턴이 어긋난다.
    """
    계획 = 손님기록.이번턴(손님, 글아이디)
    답 = {"손님": 계획["손님"], "턴": 계획["턴"], "답할까": 계획["답할까"],
          "마지막": 계획["마지막"], "그림종류": 계획["그림"],
          "글": "", "그림주소": None, "통과": False, "문제": [], "카드": "", "방향": ""}
    if not 계획["답할까"]:
        답["문제"] = ["%d턴째다. 3턴에서 끝났다" % 계획["턴"]]
        return 답

    # 번호 골라 글에 "2" 라고 적었다 (2026-09-25). 번호마다 정해진 카드를 뒤집어 준다. 1턴이다
    번호 = 번호뽑기(댓글) if (계획["턴"] == 1 and 번호글이냐(내글글)) else 0
    if 번호:
        fact = 엔진.digest("번호%d@%s" % (번호, 글아이디 or "글"), "", "결정", "지금", day, tone="반말")
        글 = 조립.번호조립(fact, 번호, 피할줄=조립.쓴줄모으기(글아이디))
        답.update({"종류": "타로", "턴셈": True, "유형": "결정", "시제": "지금", "새카드": True,
                   "글": 글, "통과": bool(글.strip()), "문제": [], "만든법": "조립(번호)",
                   "카드": fact["카드"], "방향": fact["방향"], "슬러그": fact["슬러그"],
                   "그림종류": "앞면", "그림주소": 그림올리기.앞면주소(fact["슬러그"], fact["방향"])})
        if not 답["그림주소"]:
            답["문제"], 답["통과"] = ["그림 주소가 없다"], False
        return 답

    # 칭찬·인사는 카드를 안 뽑는다. 되묻지도 않는다 (2026-09-24 사장님 지시)
    if 분류.인사냐(댓글):
        글, ok, 문제 = 인사답글(댓글)
        답.update({"종류": "인사", "글": 글, "통과": ok, "문제": 문제,
                   "그림주소": None, "그림종류": None, "턴셈": False})
        return 답
    답["종류"] = "타로"
    답["턴셈"] = True

    # 유형·시제를 안 줬으면 댓글에서 뽑는다. 낱말로 잡히면 LLM 을 안 부른다
    if not ask_type or not tense:
        본 = 분류.분류(댓글)
        if not 본["볼까"]:
            답.update({"답할까": False, "문제": ["볼 댓글이 아니다: %s" % 본["까닭"]]})
            return 답
        ask_type = ask_type or 본["유형"]
        tense = tense or 본["시제"]
        답["분류"] = 본["어떻게"]
    답.update({"유형": ask_type, "시제": tense})

    # **질문 하나에 카드 하나** (2026-09-25 사장님 지적: "매 턴마다 카드를 까는 거야?").
    #   전에는 턴마다 새 카드였다. 그러니 2턴이 "카드는 안 바꿨어" 해놓고 새 카드 얘기를 했고,
    #   5턴부터 AI 가 매번 "오늘 카드는 …" 해서 카드 자판기가 됐다.
    #   이제는
    #     1~2턴   같은 카드 (2턴은 그 카드를 더 깊게)
    #     3턴     새 카드, 뒷면 (프로필 안내)
    #     4턴~    1턴 카드로 돌아온다. AI 에게는 "이미 보여준 카드" 라고 알린다
    #     손님이 **딴 질문**(유형이 다른 물음)을 새로 던지면 그때만 새 카드
    #   글이 다르면 씨앗도 달라야 한다. 안 그러면 다른 글에서 같은 카드가 또 나온다
    바탕 = "%s@%s" % (손님, 글아이디) if 글아이디 else 손님
    오간말 = 손님기록.지난대화(손님, 글아이디=글아이디) if 계획["턴"] >= 3 else []
    씨앗이름, 고정, 새카드, 더뽑은수 = 카드정하기(
        바탕, 계획["턴"], 계획["마지막"], 댓글, ask_type, 오간말,
        손님기록.카드들(손님, 글아이디) if 계획["턴"] >= 2 else [])
    더뽑을수 = max(0, 더뽑기최대 - 더뽑은수)
    답["새카드"] = 새카드

    # **스레드 댓글은 4턴까지 AI 를 안 쓴다** (2026-09-24 사장님 지시).
    #   전에는 1턴만 조립이고 2턴부터 클로드였다. 이제 1~4턴 전부 조립이다.
    #   조립에 말결 4종(추측·짚기·받아주기·되묻기)과 끝맺는 법이 들어가 있어서
    #   네 턴까지는 파이썬만으로도 대화가 굴러간다. 토큰 0.
    #
    #   5턴부터만 AI 다. 거기는 앞 대화가 쌓여서 **문맥을 읽어야** 하는 자리고,
    #   그건 규칙으로 못 한다 — 어긋남 짚기·오래된 실 되살리기·피한 것 알아채기.
    #   여기까지 온 손님은 몇 안 되니 값도 얼마 안 든다.
    if 계획["턴"] <= AI안쓰는턴:
        fact = 엔진.digest(씨앗이름, 댓글, ask_type, tense, day, tone="반말", 고정=고정)
        # 같은 글에서 이미 나간 줄은 피한다 (2026-09-25). 구경꾼이 답글을 죽 읽는다
        피할줄 = 조립.쓴줄모으기(글아이디)
        if fact["중지"]:
            글 = fact["중지문구"]
        elif 계획["마지막"]:
            글 = 조립.마지막조립(fact, 댓글, 피할줄=피할줄)   # 3턴 — 뒷면 + 프로필 안내
        else:
            글 = 조립.조립(fact, 댓글, 계획["턴"], 피할줄=피할줄, 새카드=새카드)
        ok, 문제 = bool((글 or "").strip()), []
        답["만든법"] = "조립(마지막)" if 계획["마지막"] else "조립"
    elif 계획["마지막"]:
        글, ok, 문제, _n, fact = 쓰기(씨앗이름, 댓글, ask_type, tense, "마지막", day, tries, 조용히)
        답["만든법"] = "AI(마지막)"
    else:
        글, ok, 문제, fact = 문맥답글(씨앗이름, 댓글, ask_type, tense, day, tries,
                                      계획["턴"], 글아이디, 새카드=새카드, 고정=고정,
                                      더뽑을수=더뽑을수, 바탕=바탕, 오간말=오간말)
        답["만든법"] = "AI(문맥)"
    답.update({"글": 글, "통과": ok, "문제": 문제,
               "카드": fact["카드"], "방향": fact["방향"], "슬러그": fact["슬러그"]})

    if fact["중지"]:
        # 나이·무거운 신호. 그림도 안 붙이고 중지문구만 나간다
        답.update({"그림주소": None, "그림종류": None, "중지": True,
                   "중지까닭": fact.get("중지까닭", "")})
        return 답

    # **그림은 카드를 새로 깔 때만** (2026-09-25 사장님 지시: "이미지는 1턴만, 2·3·4턴은 안 불러온다.
    #   AI 도 마찬가지, 한 번만"). 1턴 앞면 · 한 장 더 뽑은 턴 앞면. 그 밖(2·3·4턴, 같은 카드 이어가는 AI 턴)은 글만.
    #   3턴 뒷면 그림도 안 붙인다 — 말로만 "덮어둘게" 한다.
    if 새카드 and not 계획["마지막"]:
        답["그림주소"] = 그림올리기.앞면주소(fact["슬러그"], fact["방향"])
        if not 답["그림주소"]:
            답["문제"] = list(답["문제"]) + ["그림 주소가 없다. 그림올리기.py --올리기 를 먼저"]
            답["통과"] = False
    else:
        답["그림주소"] = None
    return 답


