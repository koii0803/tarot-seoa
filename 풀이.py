def 줄수검사(글, 최대=2):
    """정해진 줄 수를 넘나 본다. 길면 아무도 안 읽는다."""
    줄들 = [x for x in (글 or "").splitlines() if x.strip()]
    if not 줄들:
        return ["글이 비었다"]
    if len(줄들) > 최대:
        return ["%d줄이다. %d줄 안으로" % (len(줄들), 최대)]
    return []


def 사람글인가(글):
    """사람이 쓴 글로 보이나. 아니면 **무조건 버린다.**"""
    t = (글 or "").strip()
    나쁜 = []
    한글 = re.sub(r"[^가-힣]", "", t)
    if len(한글) < 20:
        나쁜.append("한글이 %d자뿐이다 (껍데기로 본다)" % len(한글))
    if len(t) < 30:
        나쁜.append("글이 %d자뿐이다" % len(t))
    낮춤 = t.lower().strip(" .!?\n")
    if 낮춤 in 껍데기말:
        나쁜.append("껍데기 글이다: %r" % t[:20])
    if not re.search(r"[가-힣]", t):
        나쁜.append("한글이 하나도 없다")
    return 나쁜


def 마지막검사(글, fact):
    """3턴째 답글에만 건다. 뒤집지 않고 보내는 글이라 지켜야 할 게 따로 있다."""
    나쁜 = []
    t = 글 or ""
    # 1) 카드 이름이 새어나가면 열어볼 이유가 없어진다.
    #    짧은 이름(달·탑·별·힘)은 뒤에 '카드'가 붙을 때만 본다. 안 그러면 멀쩡한 말에 걸린다
    for c in 엔진.CARDS:
        이름 = (c.get("ko") or "").strip()
        if not 이름:
            continue
        if len(이름) >= 3:
            if 이름 in t:
                나쁜.append("카드 이름이 새어나갔다: %s" % 이름)
        elif re.search(r"%s\s*카드" % re.escape(이름), t):
            나쁜.append("카드 이름이 새어나갔다: %s" % 이름)
    # 2) 어디서 열어보는지 말해주지 않으면 이 턴을 쓰는 뜻이 없다
    if "프로필" not in t:
        나쁜.append("프로필 안내가 없다")
    # 3) 링크는 답글에 적지 않는다 (봇 규칙)
    if "http" in t or "링크" in t:
        나쁜.append("링크를 적었다")
    # 4) 재촉하면 저쪽 계정들과 똑같아진다
    for w in ("선착순", "마감", "오늘까지", "곧 닫", "서둘"):
        if w in t:
            나쁜.append("재촉하는 말: %s" % w)
    if re.search(r"(\d+\s*명(만|까지)|딱\s*\d+\s*명)", t):
        나쁜.append("수량 제한을 걸었다")
    return 나쁜


