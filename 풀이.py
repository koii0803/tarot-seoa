틀말 = ("어떻게 생각하는지", "그림이 보여주는 것까지", "오면 얘기해줄게")

# 고찰을 이론으로 늘어놓는 말 (2026-09-26 사장님: "그냥 막 던지면 이새끼 뭐지? 소리 나온다")
이론말 = ("세 종류", "세 가지 유형", "유형이", "유형은", "유형의", "사람은 원래", "사람에는", "타입이 있어", "종류가 있어")

# 사람으로 받을 땐 그림·카드 얘기를 안 한다
그림말 = ("그림", "카드")

DM말 = re.compile(r"(dm|디엠|인스타로|인스타 로)", re.I)   # "걔 인스타에" 는 안 걸리게


def 문맥답글(손님, 댓글, ask_type, tense, day=None, tries=TRIES, 턴=5, 글아이디="", 새카드=False,
             고정=None, 더뽑을수=0, 바탕="", 오간말=None, 넘겨도=False, 꼭넘겨=False, 이미넘김=False,
             속=None):
    """스레드 답글을 AI 가 쓴다. **2026-09-26 부터 1턴부터.** 지난 대화를 통째로 넘긴다.

    AI 가 댓글을 직접 읽고 알아듣는다 (낱말 분류는 카드 재료 고르기·예비용일 뿐).
    알아들은 것(topic·sensitive·wants_judgment·handoff)은 `속` dict 에 담아 돌려준다.
    검사(카드 이름·부호·AI 티·DM 아무 때나 꺼내기)는 파이썬이 본다.
    지침은 `말투.py` 하나에 모아 놨다 (웹이랑 같은 것을 쓴다).
    """
    속 = {} if 속 is None else 속
    fact = 엔진.digest(손님, 댓글, ask_type, tense, day, tone="반말", 고정=고정)
    if fact["중지"]:
        return fact["중지문구"], True, [], fact
    if 오간말 is None:
        오간말 = 손님기록.지난대화(손님, 글아이디=글아이디)
    p = 문맥프롬프트(fact, 오간말, 댓글, 새카드=새카드, 더뽑을수=더뽑을수)
    # 톤 + 끝맺는 법(되물음·남겨두기·단정) + 스레드 판단 규칙 + DM 넘김
    시킬말 = ((말투.SYS_처음 if 턴 <= 1 else 말투.SYS) + chr(10) * 2 + 말투.톤(턴)
              + chr(10) * 2 + 말투.끝맺기(턴)
              + chr(10) * 2 + 스레드판단
              + chr(10) * 2 + ((넘김꼭 if 꼭넘겨 else 넘김됨) if 넘겨도 else (넘김했음 if 이미넘김 else 넘김안됨)))
    스하리 = 분류.스하리했나(댓글)
    if 스하리:
        시킬말 += chr(10) * 2 + "이 사람이 스하리를 해줬어 니 글에 복채로 적어둔 거야 첫 줄에 땡큐 하는 결로 짧게 고맙다고 하고 바로 들어가"
    마지막, 문제 = "", ["안 돌았다"]
    for i in range(1, tries + 1):
        out = claude(p, 시킬말, schema=SCHEMA_답)
        if "__오류__" in out:
            # 시간 초과·사용량 한도 같은 것. **여기서 빈손으로 나가면 그 손님만 멈춘다**
            문제 = ["claude 오류: %s" % out["__오류__"]]
            break
        if out.get("trap"):
            # 떠보는 사람 (2026-09-26 사장님: 절대 무시). 조립 대신 쓰기로도 안 간다
            속["함정"] = True
            return "", False, ["함정: 떠보기·딴소리라 무시 (%s)" % (out.get("topic") or "")[:40]], fact
        # AI 가 스스로 새 카드를 까는 길(draw_more)은 2026-09-26 없앴다. 그림이 안 붙는 구멍이었다.
        #   새 카드는 손님이 달라거나 "한 장 더 볼까?" 에 응 했을 때만 (카드정하기)
        마지막 = 되풀이빼기(다듬기(out.get("reply") or ""), 오간말)
        # 치고 나가기 / 사람으로 받기 (2026-09-26). 첫 답은 늘 치고 나가기
        사람모드 = (out.get("mode") or "").strip().lower() == "human" and 턴 > 1
        # 사고 막는 것만 본다. 줄 수·글자 수는 말투.py 기준
        문제 = (사람글인가(마지막) + 부호검사(마지막)
                + 줄수검사(마지막, 말투.줄수)
                + (말투.글자수검사(마지막, 30, 200) if 사람모드 else 말투.글자수검사(마지막))
                + ["법으로 막힌 말: " + 막 for 막 in 말투.막힌말 if 막 in 마지막.lower()]
                + ["심문 말투: " + w for w in 심문말 if w in 마지막]
                + ["굳힌 말: " + w for w in 굳힌말 if w in 마지막]
                + [x for x in 엔진.말투검사(마지막, "반말") if not x.startswith("애교: ㅋ")])
        문제 += [x for x in 엔진.check_output(마지막, fact, need_question=False)
                 if "상징" not in x]          # 지난 대화에 나온 상징은 허용
        # DM 넘김 (2026-09-26). AI 가 handoff 를 안 켜고 DM 을 꺼내도 넘긴 걸로 본다
        민감 = bool(out.get("sensitive"))
        넘김 = bool(out.get("handoff")) or bool(DM말.search(마지막))
        if 넘김 and not 넘겨도:
            문제.append("지금은 인스타 DM 얘기를 꺼내면 안 된다")
        elif 넘김 and 민감:
            문제.append("건강·임신 같은 얘기는 DM 안내 하지 마라")
        elif 꼭넘겨 and not 민감 and not 넘김:
            문제.append("이번엔 끝에 인스타 DM 안내를 꼭 해야 한다")
        if 넘김 and not DM말.search((마지막.strip().splitlines() or [""])[-1]):
            문제.append("인스타 DM 안내가 맨 끝에 와야 한다 뒤에 딴말 붙이지 마라")
        # 그냥 "DM" 이라고만 하면 어디로 가는지 모른다 (2026-09-26 사장님)
        elif 넘김 and "인스타" not in (마지막.strip().splitlines() or [""])[-1]:
            문제.append("안내 끝줄에 꼭 '인스타 DM' 이라고 써라")
        문제 += ["틀에 박힌 말: " + w for w in 틀말 if w in 마지막]
        if sum(1 for 줄 in 마지막.splitlines() if DM말.search(줄)) > 1:
            문제.append("인스타 DM 얘기는 한 줄만")
        if 스하리 and not any(w in "".join(마지막.splitlines()[:2]) for w in ("스하리", "고마", "고맙", "땡큐", "땡스")):
            문제.append("스하리 해준 거 첫 줄에 고맙다고 받아라")
        # 댓글엔 값 얘기를 안 한다 (2026-09-26 사장님: "문지방 넘고 탈락하는 게 낫지 애초부터 탈락시키는 건 아니다").
        #   가격·결제 링크는 인스타 DM 에 들어온 뒤에 DM 쪽이 알린다
        문제 += ["댓글엔 값 얘기 빼라: " + w for w in 값말 if w in 마지막]
        문제 += ["이론처럼 늘어놓았다: " + w for w in 이론말 if w in 마지막]
        if 사람모드:
            문제 += ["사람으로 받는 답엔 그림·카드 얘기 빼라: " + w for w in 그림말 if w in 마지막]
        # "한 장 더 볼까?" 는 손님 "응" 을 받아야 하니 꼴이 정해져 있다 (손님이더달래 가 이 꼴로 알아본다)
        끝줄 = (마지막.strip().splitlines() or [""])[-1]
        #   제안은 더 볼 장이 남았고 이번에 새 카드를 안 깐 턴만 (1턴·새 카드 턴·5턴·DM 꼭 할 턴은 안 됨).
        #   안 되는 턴에 AI 가 offer_card 만 켜 놓은 건 무시한다 (시늉: 1턴에 켜서 세 번 다 걸렸다)
        제안돼 = 더뽑을수 > 0 and not 새카드
        if 제안꼴.search(끝줄) and not 제안돼:
            문제.append("이번엔 한 장 더 보자는 말을 하지 마라")
        elif 제안돼 and out.get("offer_card") and not 제안꼴.search(끝줄):
            문제.append("한 장 더 보자는 말은 마지막 줄에 '한 장 더 볼까?' 꼴로")
        if not 문제:
            속.update({"주제": (out.get("topic") or "").strip(), "민감": 민감,
                       "모드": "사람" if 사람모드 else "분석",
                       "판단원함": bool(out.get("wants_judgment")), "넘김": 넘김})
            return 마지막, True, [], fact
        p += chr(10) + chr(10) + "앞서 쓴 글이 걸렸다: %s" % " / ".join(문제) + chr(10) + "다시 써라."

    # ── AI 가 세 번 다 실패했다. **파이썬이 대신 쓴다** (2026-09-24 사장님 지시) ──
    #   전에는 빈손으로 돌아와서 그 손님만 답을 못 받고 멈췄다.
    #   실제로 @seyraen_ae 가 검사에 세 번 걸려 8시간을 기다렸다.
    #   조립은 이미 규칙을 통과한 문장이라 검사에 안 걸린다. 늦는 것보다 낫다.
    대신 = 조립.조립(fact, 댓글, 턴, 피할줄=조립.쓴줄모으기(글아이디, 손님), 새카드=새카드)
    if (대신 or "").strip():
        알림.보내기("AI 가 세 번 다 걸려서 조립으로 대신 썼다 (%d턴) · 걸린 까닭: %s"
                    % (턴, " / ".join(문제)[:150]))
        return 대신, True, ["AI 실패 → 조립으로 대신: %s" % " / ".join(문제)[:100]], fact
    return 마지막, False, 문제, fact


def 한판(손님, 댓글, ask_type=None, tense=None, day=None, tries=TRIES, 조용히=False,
         글아이디="", 내글글=""):
    """댓글 하나에 대한 답글을 **그림까지 붙여서** 내준다 (인수인계 12절 3턴 규칙).

        1~5턴  → AI 가 쓴다. 새 카드를 깐 턴만 앞면 그림 (1턴 + 더 보기 최대 2장)
                 3~4턴에 한 번 인스타 DM 안내 (답["넘김"])
        6턴~   → 답하지 않는다

    **여기서는 기록하지 않는다.** 실제로 스레드에 내보낸 뒤에
    손님기록.기록하기() 를 부른다. 안 내보냈는데 적으면 턴이 어긋난다.
    """
    계획 = 손님기록.이번턴(손님, 글아이디, 댓글)
    답 = {"손님": 계획["손님"], "턴": 계획["턴"], "답할까": 계획["답할까"],
          "마지막": 계획["마지막"], "그림종류": 계획["그림"],
          "글": "", "그림주소": None, "통과": False, "문제": [], "카드": "", "방향": ""}
    # 장난치는 사람 (사장님이 손님기록.py --무시 로 넣는다). 아무 답도 안 한다
    if 손님기록.무시하나(손님):
        답.update({"답할까": False, "문제": ["무시목록에 있는 손님"]})
        return 답
    # 5턴이 끝나도 "감사합니다" 같은 인사는 짧게 받는다 (2026-09-26 실제 손님들이 끝에 이렇게 단다)
    if not 계획["답할까"] and not (분류.인사냐(댓글) or 분류.스하리만(댓글)):
        답["문제"] = ["%d턴째다. %d턴에서 끝났다" % (계획["턴"], 손님기록.최대턴)]
        return 답

    # 하루 총량을 넘겼다 = 오늘 **딴 글에서** 이미 봐주는 사람이 새 글에 또 물었다 (2026-09-27 사장님: "사람 같아야 해").
    #   사람이면 알아본다 — "어 아까 저 글에도 물어봤지? 거기서 이어서 하자". 카드는 안 깐다.
    #   알아보는 건 하루 한 번(두 번째 글)까지. 세 번째 글부터는 조용히 둔다 — 글마다 답하면 그게 봇이다
    if 계획.get("총량넘음") and not (분류.인사냐(댓글) or 분류.스하리만(댓글)):
        if 손님기록.오늘알아본수(손님) >= 1:
            답.update({"답할까": False, "문제": ["조용히: 오늘 딴 글에서 이미 알아봤다 (세 번째 글부터 답 안 함)"]})
            return 답
        저쪽 = 손님기록.오늘딴글(손님, 글아이디)
        안내함 = 손님기록.안내했나(손님, 글아이디)
        # 저쪽 대화가 이미 끝났으면(5턴) "거기서 이어서 하자" 는 거짓말이 된다 — 거기 가도 답이 없다.
        #   DM 안내를 아직 안 했으면 DM 으로, 했으면 조용히
        저쪽끝남 = bool(저쪽) and 손님기록.지난턴(손님, 저쪽["글아이디"]) >= 손님기록.최대턴
        if 저쪽끝남 and 안내함:
            답.update({"답할까": False, "문제": ["조용히: 딴 글 대화도 끝났고 DM 안내도 이미 했다"]})
            return 답
        글, ok, 문제, 넘김 = 딴글답글(댓글, 저쪽, 안내함, 저쪽끝남=저쪽끝남)
        if 함정이냐(문제):
            답.update({"답할까": False, "문제": 문제})
            return 답
        # 그림종류 "뒷면" 은 DM 안내를 했다는 표시다 (안내했나 가 이걸로 센다). 안 했으면 안 붙인다
        답.update({"종류": "총량", "글": 글, "통과": ok, "문제": 문제, "답할까": True, "넘김": 넘김,
                   "그림주소": None, "그림종류": "뒷면" if 넘김 else None, "턴셈": False,
                   # 저쪽 답이 아직 대기 중이면 그보다 늦게 나가야 "거기서 이어서 하자" 가 말이 된다
                   "딴글나갈때": "" if not 저쪽 else 저쪽.get("나갈때", "")})
        return 답
    # 번호 골라 글에 "2" 라고 적었다 (2026-09-25). 번호마다 정해진 카드를 뒤집어 준다. 1턴이다
    번호 = 번호뽑기(댓글) if (계획["턴"] == 1 and 번호글이냐(내글글)) else 0
    if 번호:
        fact = 엔진.digest("번호%d@%s" % (번호, 글아이디 or "글"), "", "결정", "지금", day, tone="반말")
        글 = 조립.번호조립(fact, 번호, 피할줄=조립.쓴줄모으기(글아이디, 손님))
        답.update({"종류": "타로", "턴셈": True, "유형": "결정", "시제": "지금", "새카드": True,
                   "글": 글, "통과": bool(글.strip()), "문제": [], "만든법": "조립(번호)",
                   "카드": fact["카드"], "방향": fact["방향"], "슬러그": fact["슬러그"],
                   "그림종류": "앞면", "그림주소": 그림올리기.앞면주소(fact["슬러그"], fact["방향"])})
        if not 답["그림주소"]:
            답["문제"], 답["통과"] = ["그림 주소가 없다"], False
        return 답

    # 칭찬·인사는 카드를 안 뽑는다. 되묻지도 않는다 (2026-09-24 사장님 지시)
    # 스하리만 한 것도 여기로 (2026-09-26: 복채 낸 사람을 "품앗이 댓글" 로 버리고 있었다)
    if 분류.인사냐(댓글) or 분류.스하리만(댓글):
        글, ok, 문제 = 인사답글(댓글, 스하리=분류.스하리만(댓글))
        if 함정이냐(문제):
            답.update({"답할까": False, "문제": 문제})
            return 답
        답.update({"종류": "인사", "글": 글, "통과": ok, "문제": 문제, "답할까": True,
                   "그림주소": None, "그림종류": None, "턴셈": False})
        return 답
    답["종류"] = "타로"
    답["턴셈"] = True

    # 유형·시제를 안 줬으면 댓글에서 뽑는다. **분류 AI 는 안 부른다** (2026-09-26).
    #   답글 쓰는 AI 가 댓글을 직접 읽는다. 여기 유형은 카드 재료 고르기·예비 조립용일 뿐이다
    if not ask_type or not tense:
        본 = 분류.분류(댓글, haiku써도되나=False)
        # 대화 중(2턴~)엔 "응" "응 봐줘" 같은 짧은 답도 받는다 (2026-09-26 시늉: 한 장 더 볼까? 에 "응 봐줘" 를 버렸다).
        #   링크 달린 것만 여전히 거른다
        if not 본["볼까"] and (계획["턴"] == 1 or "링크" in 본["까닭"] or "빈 댓글" in 본["까닭"]):
            답.update({"답할까": False, "문제": ["볼 댓글이 아니다: %s" % 본["까닭"]]})
            return 답
        ask_type = ask_type or 본["유형"] or "결정"
        tense = tense or 본["시제"] or "지금"
        답["분류"] = 본["어떻게"]
    답.update({"유형": ask_type, "시제": tense})

    # **질문 하나에 카드 하나** (2026-09-25 사장님 지적: "매 턴마다 카드를 까는 거야?").
    #   전에는 턴마다 새 카드였다. 그러니 2턴이 "카드는 안 바꿨어" 해놓고 새 카드 얘기를 했고,
    #   5턴부터 AI 가 매번 "오늘 카드는 …" 해서 카드 자판기가 됐다.
    #   이제는
    #     1~2턴   같은 카드 (2턴은 그 카드를 더 깊게)
    #     3턴     새 카드, 뒷면 (프로필 안내)
    #     4턴~    1턴 카드로 돌아온다. AI 에게는 "이미 보여준 카드" 라고 알린다
    #     손님이 **딴 질문**(유형이 다른 물음)을 새로 던지면 그때만 새 카드
    #   글이 다르면 씨앗도 달라야 한다. 안 그러면 다른 글에서 같은 카드가 또 나온다
    바탕 = "%s@%s" % (손님, 글아이디) if 글아이디 else 손님
    오간말 = 손님기록.지난대화(손님, 글아이디=글아이디) if 계획["턴"] >= 2 else []
    씨앗이름, 고정, 새카드, 더뽑은수 = 카드정하기(
        바탕, 계획["턴"], 계획["마지막"], 댓글, ask_type, 오간말,
        손님기록.카드들(손님, 글아이디) if 계획["턴"] >= 2 else [])
    # 마지막 턴엔 다음이 없으니 "한 장 더 볼까?" 를 안 한다. DM 안내를 꼭 해야 하는 턴도 (안내가 맨 끝이라)
    더뽑을수 = (0 if 계획["턴"] >= 손님기록.최대턴 or 계획["꼭넘겨"]
               else max(0, 더뽑기최대 - 더뽑은수))
    답["새카드"] = 새카드

    # **스레드 댓글은 1턴부터 AI 가 쓴다** (2026-09-26 사장님 지시).
    #   전에는 1~4턴 조립(파이썬), 3턴 가림, 5턴부터 AI 였다.
    #   조립은 낱말로 주제를 잡아서 "시험관" 을 "시험" 으로 읽었다. 첫 답에서 헛짚으면 끝이다.
    #   이제 AI 가 댓글을 직접 읽고 쓰고, 파이썬은 검사만 한다. AI 가 세 번 다 실패하면 조립이 대신 쓴다.
    #   3턴 가림도 없앴다. 3~4턴에 문맥 맞춰 인스타 DM 안내를 한 번 한다 (4턴~ 아직이면 꼭).
    #   값·결제는 댓글에서 말하지 않는다. DM 에 들어오면 DM 쪽이 결제 링크를 보낸다
    #   새 카드를 까는 턴엔 안 한다 — 그림 붙이고 바로 "DM 와" 하면 영업이 된다.
    # 새 카드 턴엔 DM 안내를 안 한다. 단 마지막 턴(5)은 다음이 없으니 한다
    막턴아니면새카드아님 = (not 새카드) or 계획["턴"] >= 손님기록.최대턴
    속 = {}
    글, ok, 문제, fact = 문맥답글(씨앗이름, 댓글, ask_type, tense, day, tries,
                                  계획["턴"], 글아이디, 새카드=새카드, 고정=고정,
                                  더뽑을수=더뽑을수, 바탕=바탕, 오간말=오간말,
                                  넘겨도=계획["넘겨도"] and 막턴아니면새카드아님,
                                  꼭넘겨=계획["꼭넘겨"] and 막턴아니면새카드아님,
                                  이미넘김=계획["안내함"], 속=속)
    if 속.get("함정"):                  # 답 안 함 → 대기표에 '안함' 으로만 남는다 (알림 없음)
        답.update({"답할까": False, "문제": 문제})
        return 답
    답["만든법"] = "중지" if fact["중지"] else ("AI" if 속 else "조립(AI 실패)")
    답.update({"글": 글, "통과": ok, "문제": 문제,
               "카드": fact["카드"], "방향": fact["방향"], "슬러그": fact["슬러그"],
               "주제": 속.get("주제", ""), "민감": 속.get("민감", False),
               "판단원함": 속.get("판단원함", False), "넘김": 속.get("넘김", False),
               "모드": 속.get("모드", "")})
    if 답["넘김"]:
        # 손님기록에 "뒷면" 으로 적혀야 안내했나() 가 잡아서 두 번 안 넘긴다
        답["그림종류"], 답["마지막"] = "뒷면", True

    if fact["중지"]:
        # 나이·무거운 신호. 그림도 안 붙이고 중지문구만 나간다
        답.update({"그림주소": None, "그림종류": None, "중지": True,
                   "중지까닭": fact.get("중지까닭", "")})
        return 답

    # **그림은 카드를 새로 깔 때만** (2026-09-25 사장님 지시: "이미지는 1턴만, 2·3·4턴은 안 불러온다.
    #   AI 도 마찬가지, 한 번만"). 1턴 앞면 · 한 장 더 뽑은 턴 앞면. 그 밖(2·3·4턴, 같은 카드 이어가는 AI 턴)은 글만.
    #   3턴 뒷면 그림도 안 붙인다 — 말로만 "덮어둘게" 한다.
    if 새카드 and not 계획["마지막"]:
        답["그림주소"] = 그림올리기.앞면주소(fact["슬러그"], fact["방향"])
        if not 답["그림주소"]:
            답["문제"] = list(답["문제"]) + ["그림 주소가 없다. 그림올리기.py --올리기 를 먼저"]
            답["통과"] = False
    else:
        답["그림주소"] = None
    return 답


