def 오늘쓴양(손님, 글아이디=""):
    """오늘(서울) 이 사람이 **다른 글에서** 연 대화 수 · 받은 번호 카드 수. 대기 중인 것도 센다."""
    키 = _손님키(손님)
    오늘 = 지금().date()
    대화글, 번호 = set(), 0
    줄들 = [x for x in _읽기() if x.get("손님") == 키 and x.get("종류", "타로") == "타로"]
    줄들 += [dict(x, 글아이디=x.get("내글", "")) for x in _대기중(키) if (x.get("종류") or "타로") == "타로"]
    for x in 줄들:
        때 = _때(x)
        if not 때 or 때.date() != 오늘:
            continue
        g = x.get("글아이디") or ""
        if x.get("턴", 1) == 1 and 번호꼴.match(x.get("댓글") or ""):
            번호 += 1
        elif g and g != 글아이디:
            대화글.add(g)
    return len(대화글), 번호


def 오늘딴글(손님, 글아이디=""):
    """오늘(서울) 이 사람이 **다른 글에서** 먼저 연 대화. 없으면 None (2026-09-27).

    같은 사람이 글마다 같은 걸 물을 때 "어 아까 저 글에도 물어봤지?" 하려고 쓴다.
    {"글아이디", "댓글"(저쪽 첫 댓글), "나감"(저쪽 답이 나갔나), "나갈때"(아직이면 언제), "번호"}
    """
    키 = _손님키(손님)
    오늘 = 지금().date()
    모음 = {}
    줄들 = [dict(x, 나감=True) for x in _읽기() if x.get("손님") == 키]
    줄들 += [dict(x, 글아이디=x.get("내글", ""), 나감=False) for x in _대기중(키)]
    for x in 줄들:
        if (x.get("종류") or "타로") != "타로" or x.get("채널관리"):
            continue
        때 = _때(x)
        g = x.get("글아이디") or ""
        if not 때 or 때.date() != 오늘 or not g or g == 글아이디:
            continue
        있던것 = 모음.get(g)
        if 있던것 is None or 때 < 있던것["때"]:
            모음[g] = {"글아이디": g, "댓글": (x.get("댓글") or "").strip(), "때": 때,
                      "나감": x["나감"] or bool(있던것 and 있던것["나감"]),
                      "나갈때": "" if x["나감"] else (x.get("나갈때") or ""),
                      "번호": bool(번호꼴.match(x.get("댓글") or ""))}
        elif x["나감"]:
            있던것["나감"], 있던것["나갈때"] = True, ""
    if not 모음:
        return None
    return min(모음.values(), key=lambda v: v["때"])


def 오늘알아본수(손님):
    """오늘 딴 글에서 "아까 저 글에 물어봤지" 로 받아준 횟수 (종류 총량). 대기 중인 것도 센다."""
