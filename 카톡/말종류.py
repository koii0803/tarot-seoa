# -*- coding: utf-8 -*-
"""손님 말이 **어떤 종류인지** 가른다 (2026-09-24 사장님 지시).

왜 필요한가
    전에는 손님이 한 마디 할 때마다 카드를 새로 뽑았다. 한 상담에 카드가 스무 장씩 나왔다.
    그러면 카드가 의미를 잃는다. 직접 라인은 더 나쁘다 — 말 한 마디마다 사이트로 보냈다.

    실제 타로는 **질문 하나에 카드 한 장**이고, 그 한 장을 놓고 몇 턴이든 얘기한다.
    그래서 "지금 이 말이 앞 카드 얘기인가, 새 주제인가" 를 가려야 한다.

왜 낱말로 안 하나
    사장님: "하나 더, 다른 것도 <- 이렇게 물어볼까?"
    안 그런다. 손님은 그냥 다음 고민을 던진다. "회사도 요즘 다니기 싫어" 처럼.
    타로를 모르는 사람은 **카드를 한 장 더 뽑아야 한다는 개념 자체가 없다.**
    그래서 낱말로 잡으려 하면 끝이 없다. 하이쿠한테 종류만 묻는다. 싸고 빠르다.

애매하면
    사장님: "애매하다 싶으면 먼저 물어봐도 되잖아"
    맞다. **틀리게 뽑느니 묻는다.** 대화하고 싶은데 새 카드를 뽑아 버리거나,
    새 주제인데 옛 카드로 답하면 둘 다 망한다. 손님이 버튼 한 번 누르는 게 낫다.

표준 라이브러리만 쓴다.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys

MODEL = "sonnet"         # 2026-09-24 사장님 지시. haiku 는 출력이 튀어서 값이 안 쌌다

# 카드를 그대로 들고 가는 종류들
카드유지 = ("이어묻기", "카드질문", "불신", "시기", "감정", "예아니오")
# 카드를 새로 뽑는 종류
새카드 = ("다시뽑기", "제3자")
# 카드와 상관없는 종류
딴것 = ("값질문", "봇질문", "마무리", "잡담")

종류들 = 카드유지 + 새카드 + 딴것 + ("새주제", "애매")

SCHEMA = {
    "type": "object",
    "properties": {"kind": {"type": "string"}},
    "required": ["kind"],
}

SYS = """너는 타로 상담 손님의 말이 **어떤 종류인지** 가르는 기계다. 설명하지 말고 값만 낸다.

지금 상황: 손님은 이미 카드 한 장을 받았고, 그 카드로 얘기하는 중이다.
가려야 할 것은 하나다 — **이 말이 그 카드 얘기인가, 아니면 새로 뽑아야 하는가.**

kind 는 반드시 이 중 하나다

  카드를 그대로 쓰는 것
    이어묻기   앞 얘기를 더 파고든다. "그럼 먼저 연락해도 돼" "어떻게 해야 돼"
    카드질문   카드 자체를 묻는다. "그 카드 무슨 뜻이야" "역방향이면 나쁜 거야"
    불신       못 믿겠다고 한다. "이거 맞아?" "안 믿겨" "다 그렇게 말하잖아"
    시기       언제냐고 묻는다. "언제쯤 그렇게 돼" "올해 안에 될까"
    감정       그냥 털어놓는다. "너무 힘들어" "요즘 잠이 안 와"
    예아니오   단정을 요구한다. "된다는 거야 만다는 거야" "그래서 될까 안 될까"

  카드를 새로 뽑아야 하는 것
    다시뽑기   이 카드 말고 다시 달라고 한다. "다시 뽑아줘" "마음에 안 들어"
    제3자      다른 사람 것을 묻는다. "내 친구도 봐줘" "엄마 것도"

  카드와 상관없는 것
    값질문     돈 얘기. "얼마야" "유료야" "결제해야 돼"
    봇질문     정체를 묻는다. "너 사람이야" "AI야" "진짜 타로 봐주는 거야"
    마무리     끝내는 말. "고마워" "잘 자" "도움 됐어"
    잡담       내용이 없다. "ㅋㅋㅋ" "ㅇㅇ" "그렇구나"

  그 밖에
    새주제     앞 카드와 **분명히 다른 고민**을 새로 꺼낸다.
               앞이 재회 얘기였는데 "회사 그만둘까" 로 넘어가는 식이다.
    애매       새 주제인지 이어묻기인지 **헷갈린다.** 조금이라도 헷갈리면 이것을 골라라.

**헷갈리면 무조건 애매다.** 틀리게 고르는 것보다 애매가 낫다.
앞 카드 얘기를 더 하고 싶은 손님한테 새 카드를 뽑아 버리면 대화가 끊긴다."""


def _하이쿠(앞대화, 이번말, timeout=60):
    p = """지금까지 오간 말
%s

방금 손님이 한 말
    %s

kind 만 내라.""" % (앞대화 or "    (없음)", 이번말)
    cmd = ["claude", "-p", p, "--output-format", "json",
           "--json-schema", json.dumps(SCHEMA, ensure_ascii=False),
           "--model", MODEL, "--safe-mode", "--system-prompt", SYS,
           "--tools", "Read", "--disallowedTools", "Read"]
    try:
        r = subprocess.run(cmd, capture_output=True, timeout=timeout,
                           encoding="utf-8", errors="replace",
                           stdin=subprocess.DEVNULL)
        if r.returncode != 0:
            return None
        out = json.loads(r.stdout)
        본문 = out.get("result", out)
        if isinstance(본문, str):
            본문 = json.loads(본문)
        값 = (본문.get("kind") or "").strip()
        return 값 if 값 in 종류들 else None
    except Exception:
        return None


# 하이쿠를 안 불러도 확실한 것들. 돈 0
_다시뽑기 = re.compile(r"(다시\s*뽑|새로\s*뽑|한\s*장\s*더|다른\s*카드|마음에\s*안\s*들)")
_값질문 = re.compile(r"(얼마|유료|무료\s*야|결제|돈\s*내|가격|비용)")
_봇질문 = re.compile(r"(너\s*사람|사람이야|AI|에이아이|봇이야|기계야|진짜\s*사람)", re.I)
_마무리 = re.compile(r"^(고마워|고맙|감사|잘\s*자|안녕히|수고|도움\s*됐|잘\s*봤)")


def 가르기(앞대화, 이번말, 하이쿠써도되나=True):
    """(종류, 어떻게) 를 낸다. 낱말로 잡히면 AI 를 안 부른다."""
    t = (이번말 or "").strip()
    if not t:
        return "잡담", "글자"
    if _다시뽑기.search(t):
        return "다시뽑기", "말"
    if _값질문.search(t):
        return "값질문", "말"
    if _봇질문.search(t):
        return "봇질문", "말"
    if _마무리.match(t):
        return "마무리", "말"

    if not 하이쿠써도되나:
        return "애매", "안물어봄"
    값 = _하이쿠(앞대화, t)
    return (값, "AI") if 값 else ("애매", "AI실패")


def 시험():
    보기 = [
        ("그럼 내가 먼저 연락해도 돼", "이어묻기"),
        ("그 카드 무슨 뜻이야", "카드질문"),
        ("이거 진짜 맞아 안 믿겨", "불신"),
        ("언제쯤 그렇게 될까", "시기"),
        ("나 요즘 잠도 안 오고 너무 힘들어", "감정"),
        ("그래서 된다는 거야 안 된다는 거야", "예아니오"),
        ("회사 그만둘까 고민이야", "새주제"),
        ("다시 뽑아줘", "다시뽑기"),
        ("내 친구 것도 봐줄 수 있어", "제3자"),
        ("이거 얼마야", "값질문"),
        ("너 사람이야", "봇질문"),
        ("고마워 도움 됐어", "마무리"),
    ]
    앞 = "    손님: 3년 사귄 남자친구랑 헤어졌는데 재회될까\n    나: 죽음 역방향이야 끝난 걸 습관으로 쥐고 있는 때"
    맞음 = 0
    for 말, 정답 in 보기:
        값, 어떻게 = 가르기(앞, 말)
        ok = (값 == 정답)
        맞음 += ok
        print("  %s %-10s (정답 %-6s · %s) | %s" %
              ("O" if ok else "X", 값, 정답, 어떻게, 말))
    print("%d/%d" % (맞음, len(보기)))
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(시험())
