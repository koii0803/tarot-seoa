def 이번결(fact, 턴):
    """이번 턴의 결.

    **차례를 고정한 목록 위에서 턴만큼 돌린다.** 전에는 턴마다 쓸 수 있는 결 개수가
    달라져서 나머지 계산이 어긋났고, 그 바람에 2턴·3턴이 연달아 "추측" 으로 나왔다.
    이제는 목록을 고정해 놓고, 못 쓰는 결이 걸리면 다음 것으로 넘어간다.
    """
    씨 = abs(hash((fact.get("슬러그") or "") + str(fact.get("날짜") or ""))) % 97
    for 더 in range(len(말결들)):
        결 = 말결들[(씨 + 턴 + 더) % len(말결들)]
        if 쓸수있나(결, fact, 턴):
            return 결
    return "되묻기"


