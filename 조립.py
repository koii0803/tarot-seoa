def 시험():
    print("AI 안 부르고 조립한 1턴 답글 (토큰 0)\n")
    for 손님, 댓글, t, ts in 시험댓글:
        글, fact = 한판조립(손님, 댓글, t, ts)
        print("@%s: %s" % (손님, 댓글))
        print("  [%s %s]" % (fact["카드"], fact["방향"]))
        for line in 글.splitlines():
            print("  " + line)
        print()
    return 0


def main():
    ap = argparse.ArgumentParser(description="1턴 답글 조립")
    ap.add_argument("--시험", action="store_true")
    ap.add_argument("--댓글", metavar="글")
    ap.add_argument("--손님", default="손님")
    ap.add_argument("--type", default="결정")
    ap.add_argument("--tense", default="지금")
    a = ap.parse_args()
    if a.시험:
        return 시험()
    if a.댓글:
        글, fact = 한판조립(a.손님, a.댓글, a.type, a.tense)
        print("[%s %s]" % (fact["카드"], fact["방향"]))
        print(글)
        return 0
    ap.print_help()
    return 0


