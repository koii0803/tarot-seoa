def 조사고르기(앞말, 받침있을때):
    """받침 있으면 앞엣것, 없으면 짝을 준다. (은/는, 이/가 …)"""
    없을때 = 조사짝.get(받침있을때, 받침있을때)
    끝글자 = (앞말 or "").strip()[-1:] if (앞말 or "").strip() else ""
    return 받침있을때 if 받침있나(끝글자) else 없을때


def 조사맞추기(글):
    """`{말}{은}` 꼴로 적어 둔 자리를 실제 말에 맞춰 바꾼다."""
    def 바꿈(m):
        앞, 조사 = m.group(1), m.group(2)
        return 앞 + 조사고르기(앞, 조사)
    # 낱말 바로 뒤에 붙은 조사만 본다
    붙임 = "|".join(sorted(조사짝, key=len, reverse=True))
    return re.sub(r"([가-힣0-9]+)\{(%s)\}" % 붙임, 바꿈, 글)


def _부호치우기(글):
    남길것 = re.compile(r"[^\w\s가-힣?]", re.UNICODE)
    줄들 = []
    for 줄 in (글 or "").splitlines():
        줄 = 남길것.sub(" ", 줄)
        줄 = re.sub(r"\s+", " ", 줄).strip()
        if 줄:
            줄들.append(줄)
    return "\n".join(줄들)


