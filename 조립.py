    # 2턴은 다른 종류. 상대 마음(1)은 연애·재회·관계일 때만 (불안 질문에 "그 사람은" 하면 헛소리다)
    나머지 = [x for i, x in enumerate(벌) if i != 첫째 and (i != 1 or 유형 in ("연애", "재회", "관계"))]
    return 고르기(나머지 or 벌)


