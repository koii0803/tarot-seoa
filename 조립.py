# ── 짚기 — 손님이 **안 적은 걸** 짚는다 (2026-09-24 신설) ──────────────────
#
# 팔자오빠에서 사람으로 보이게 만든 것 중 두 번째로 큰 레버다.
# 사주는 생년월일에서 뽑지만 **타로는 이 사람이 쓴 문장에서 뽑는다.**
#
# 맞히는 게 아니라 **문장 형태를 짚는 것**이라 틀릴 일이 적다.
# 그리고 **단정하지 않는다** — "~같은데" "~나보네" 로 끝낸다 (팔자오빠 프롬프트 규칙).
# 신호가 하나도 안 걸리면 이 칸을 **비운다.** 억지로 짚으면 헛소리가 된다.
기간꼴 = re.compile(r"(\d+\s*(?:년|달|개월|주일|주|일)\s*(?:반)?)")
# 자기 얘기가 들어 있나. **없으면** 상대 얘기만 하고 있는 것
자기말 = re.compile(r"((^|\s)(나|내|난|제|저|우리)(\s|$)|나는|내가|나도|나만|제가|저는|"
                   r"힘들|싫|무섭|겁|걱정|불안|답답|서운|화나|밉|그립|싶|괴롭|외로|속상|지쳐|버겁)")
미래꼴 = re.compile(r"(될까|올까|할까|갈까|생길까|붙을까|나을까|괜찮을까|될지|올지)")
물음꼴 = re.compile(r"(\?|까요|나요|가요|어요\s*$|은가|을까|ㄹ까|까$)")


def _짚기(fact, 댓글, 몇개=1):
    """문장에서 잡히는 신호를 짚는다. 없으면 빈 줄.

    **맞히는 게 아니라 문장 형태를 짚는 것**이라 틀릴 일이 적다.
    신호가 없으면 억지로 짚지 않는다 — 그러면 헛소리가 된다.
    """
    t = (댓글 or "").strip()
    후보 = []

    m = 기간꼴.search(t)
    if m:
        기간 = m.group(1).replace(" ", "")
        후보.append(고르기(["%s이라고 적은 거 보니 세고 있었나보네" % 기간,
                        "%s까지 세고 있었구나" % 기간,
                        "%s이라는 숫자가 먼저 나온 게 걸리네" % 기간], True))
    if t and not 물음꼴.search(t):
        후보.append(고르기(["묻는 게 아니라 확인받고 싶은 거 같은데",
                        "물음표가 없네 답은 이미 있고 확인만 남은 거지",
                        "묻는 말이 아니라 정해놓고 온 말 같은데"], True))
    if "그냥" in t:
        후보.append(고르기(["그냥이라고 적었는데 그냥인 적은 없었을 거야",
                        "그냥이라는 말이 제일 안 그냥이더라"], True))
    if not 자기말.search(t) and len(t) >= 8 and (물음꼴.search(t) or 미래꼴.search(t)):
        # 묻는 말일 때만. "걔가 먼저 헤어지자고 했거든" 에 "결과만 묻고" 라고 하면 헛소리다 (2026-09-25 10턴 시늉)
        # "그 사람" 이 있는 질문(연애·재회·관계)만 상대 얘기라고 짚는다.
        # 면접·직장 질문에 "그 사람 얘기뿐" 이라고 하면 헛소리다 (2026-09-25 실측)
        if fact.get("질문유형") in 속마음유형:
            후보.append(고르기(["그쪽 얘기만 있고 니 얘기가 없네",
                            "그 사람 얘기뿐이고 니 마음은 한 글자도 없어",
                            "상대 얘기만 적었네 니는 어디 있어",
                            "니 얘기는 빼놓고 물었구나"], True))
        else:
            후보.append(고르기(["될지만 있고 니 마음은 없네",
                            "결과만 묻고 니 얘기는 한 줄도 없어",
                            "니가 어떤지는 빼놓고 물었구나"], True))
    if 미래꼴.search(t):
        후보.append(고르기(["될지를 묻는데 하고 싶은지는 안 적었어",
                        "될까만 있고 하고 싶은지는 없네",
                        "되냐고 묻기 전에 원하는지부터 안 적었어",
                        "될지보다 니가 그걸 바라는지가 먼저 안 보여"], True))
    후보 = [x for x in 후보 if x]        # 다 써서 비운 칸은 뺀다
    if not 후보:
        return []
    random.shuffle(후보)
    return 후보[:몇개]


def _기울기줄(fact, 댓글):
    """될까·올까 물음이면 카드가 어느 쪽으로 기우는지 한 줄 (2026-09-25).

    물음이 아니면 안 만든다. 단정하지 않는다 — 데이터가 전부 "기울어·쪽이야" 꼴이다.
    """
    t = (댓글 or "").strip()
    if not (미래꼴.search(t) or 물음꼴.search(t) or "궁금" in t):
        return ""
    칸 = 기울기.get(fact.get("슬러그") or "")
    것 = fact.get("기울기벌") or ((칸.get(fact.get("방향") or "정방향") if isinstance(칸, dict) else None) or {})
    줄들 = list(것.get("줄") or [])
    if not 줄들:
        return ""
    # 뜻줄이랑 같은 말이 겹치면 두 줄이 앵무새가 된다. 겹치는 건 뒤로 뺀다
    # 카드말이 있으면 뜻 3벌 전부와 견준다 (어느 뜻이 뽑히든 안 겹치게. 2026-09-26)
    뜻들 = list(fact.get("뜻벌") or []) or [_한줄줄이기(fact)]
    조각 = [뜻[i:i+4] for 뜻 in 뜻들 for i in range(0, max(1, len(뜻) - 3), 2)]
    조각 = [c for c in 조각 if len(c.replace(" ", "")) >= 3 and c.strip() not in ("이야", "거야", "쪽이야", "아니야", "아니라")]
    안겹침 = [x for x in 줄들 if not any(c in x for c in 조각)]
    return 고르기(안겹침 or 줄들)


def _한줄줄이기(fact):
    """카드 뜻 한 줄. **반말판이 있으면 그걸 쓴다.**

    엔진이 주는 뜻은 사이트용 존댓말이라 조립글에 박으면 말투가 섞인다
    ("균형이 무너진 채 달리고 있습니다"). 반말판은 미리 굳혀 둔 것이라 토큰이 안 든다.
    """
    if fact.get("뜻벌"):                     # 카드말 (2026-09-26). 이름 없이 상황으로 말하는 뜻
        return 고르기(fact["뜻벌"]) or (fact.get("한줄") or "").strip()
    것 = 반말뜻.get(fact.get("슬러그") or "")
    if isinstance(것, dict):
        말 = 것.get(fact.get("방향") or "정방향")
        if 말:
            return 말.strip()
    t = re.split(r"[.,·\n]", (fact.get("한줄") or "").strip())[0].strip()
    t = re.sub(r"(입니다|습니다|해요|예요)$", "", t)
    return t[:40]


