# 칸을 고를 때 거기 없는 것부터 쓴다. 다 썼으면 그냥 고른다 (안 쓰는 것보다 낫다).
# 틀에 {상징} 같은 빈칸이 있으면 빈칸 뺀 나머지 글자가 겹치는지로 본다.
_피할줄 = set()          # 조립() 이 들어올 때 채우고 나갈 때 비운다


def _자국(틀):
    """틀에서 빈칸을 뺀 글자 조각들. "{한줄} 딱 거기야" → ["딱 거기야"] """
    return [x.strip() for x in re.split(r"\{[^}]*\}", 틀 or "") if x.strip()]


def _썼나(틀):
    자국 = _자국(틀)
    if not 자국:
        return False
    return any(all(조각 in 줄 for 조각 in 자국) for 줄 in _피할줄)


def 고르기(후보들, 다썼으면비움=False):
    """random.choice 대신 쓴다. 이 글에서 안 쓴 것부터 고른다.

    `다썼으면비움` 은 없어도 되는 칸(짚기)에 쓴다. 다 썼으면 같은 말 또 하느니 그 칸을 비운다.
    """
    후보들 = [x for x in 후보들 if x]
    if not 후보들:
        return ""
    남은것 = [x for x in 후보들 if not _썼나(x)]
    if not 남은것 and 다썼으면비움:
        return ""
    return random.choice(남은것 or 후보들)


def 쓴줄모으기(글아이디):
    """그 글에서 이미 나갔거나 나갈 답글의 줄 전부. 풀이.한판 이 부른다.

    손님기록·대기표는 R2 창고를 읽는다. 창고를 못 읽어도 조립은 돌아야 하니 빈 집합으로 떨어진다.
    """
    if not 글아이디:
        return set()
    줄들 = set()
    try:
        import 손님기록
        for x in 손님기록._읽기():
            if x.get("글아이디") == 글아이디:
                줄들.update(l.strip() for l in (x.get("글") or "").splitlines() if l.strip())
    except Exception:
        pass
    try:
        import 대기표
        for x in 대기표.읽기():
            if x.get("내글") == 글아이디 and x.get("상태") == "대기":
                줄들.update(l.strip() for l in (x.get("글") or "").splitlines() if l.strip())
    except Exception:
        pass
    return 줄들


