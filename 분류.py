    for 댓글, 정답 in 시험댓글:
        r = 분류(댓글, haiku써도되나)
        ok = r["유형"] == 정답
        맞음 += ok
        print("  %s %-6s (정답 %-4s, %s) %s" % ("O" if ok else "X", r["유형"], 정답,
                                                r["시제"], 댓글[:34]))
    print("  → %d / %d" % (맞음, len(시험댓글)))
    print("\n안 보고 넘겨야 할 것")
    for 댓글 in 안볼것:
        r = 분류(댓글, False)
        print("  %s %-24s %s" % ("O" if not r["볼까"] else "X", repr(댓글)[:26], r["까닭"]))
