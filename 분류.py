def 인사냐(댓글):
    """칭찬·인사인가. 물음표가 있으면 질문으로 본다(칭찬하면서 묻는 사람도 있다)."""
    t = (댓글 or "").strip()
    if "?" in t:
        return False
    낮춤 = t.lower().replace(" ", "")
    if not any(w.replace(" ", "") in 낮춤 for w in 인사말):
        return False
    # 사연이 길면 칭찬이 아니라 상담이다
    한글 = re.sub(r"[^가-힣]", "", t)
    return len(한글) <= 25


def 볼만한가(댓글):
    """LLM 을 부를 값어치가 있는 댓글인가. (볼까, 까닭)"""
    t = (댓글 or "").strip()
    if not t:
        return False, "빈 댓글"
    if "http" in t.lower() or "www." in t.lower():
        return False, "링크가 있다"
    낮춤 = t.lower().replace(" ", "")
    # **품앗이 말이 있어도 뒤에 진짜 질문이 있으면 본다** (2026-09-24 실측으로 고침).
    #   버려진 것 중에 이런 게 있었다 —
    #   "스하리 완 다음주에 전남친이 있는 술자리에 가면 재회가 가능할까요?"
    #   앞에 인사만 붙였을 뿐 진짜 손님인데 통째로 버리고 있었다.
    걸린품앗이 = next((w for w in 품앗이말 if w.replace(" ", "") in 낮춤), "")
    if 걸린품앗이 and not 질문남았나(t):
        return False, "품앗이·영업 댓글이다(%s)" % 걸린품앗이
    # 글자(한글·영문·숫자)가 몇 개나 되나. 이모지·자음만 있는 것은 뺀다
    알맹이 = re.sub(r"[^0-9A-Za-z가-힣]", "", t)
    if len(알맹이) < 최소글자:
        return False, "너무 짧다(글자 %d개)" % len(알맹이)
    if re.fullmatch(r"[ㄱ-ㅎㅏ-ㅣ]+", 알맹이):
        return False, "자음·모음뿐"
    return True, ""


