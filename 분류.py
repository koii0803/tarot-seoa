def 질문남았나(댓글):
    """품앗이 말을 지우고도 질문이 남으면 진짜 손님이다."""
    남은것 = 댓글 or ""
    for w in 품앗이말:
        남은것 = 남은것.replace(w, " ")
    알맹이 = re.sub(r"[^0-9A-Za-z가-힣]", "", 남은것)
    if len(알맹이) < 8:
        return False                     # 인사만 하고 끝난 것
    return bool(물음꼴.search(남은것))


